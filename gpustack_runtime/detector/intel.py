logger = logging.getLogger(__name__)

_XPU_SMI_TIMEOUT = 20


def _run_xpu_smi(*args: str) -> str:
    out = subprocess.run(  # noqa: S603
        [shutil.which("xpu-smi") or "xpu-smi", *args],
        capture_output=True,
        text=True,
        timeout=_XPU_SMI_TIMEOUT,
        check=True,
    )
    return out.stdout


def bdf_to_cdi_uid(bdf: str, pci_device_id: str) -> str:
    """
    Intel CDI device name (as generated by `intel-cdi-specs-generator` and the
    Intel GPU resource driver), e.g. `0000:2b:00.0` + `0xe211` ->
    `0000-2b-00-0-0xe211`.
    """
    return f"{bdf.replace(':', '-').replace('.', '-')}-{pci_device_id}"


def collect_from_xpu_smi() -> dict[str, dict]:
    """
    Collect the physical cards with the `xpu-smi` CLI, keyed by PCI BDF.
    Static info works for any user; the usage metrics need the MEI devices
    (root).
    """
    listing = json.loads(_run_xpu_smi("discovery", "-j")).get("device_list", [])
    cards: dict[str, dict] = {}
    by_id: dict[int, str] = {}
    for dev in listing:
        if dev.get("device_type") not in (None, "GPU"):
            continue
        if dev.get("device_function_type") not in (None, "physical"):
            continue
        bdf = dev["pci_bdf_address"]
        by_id[int(dev["device_id"])] = bdf
        card = cards.setdefault(bdf, {"bdf": bdf})
        card["name"] = dev.get("device_name")
        card["vendor"] = dev.get("vendor_name")
        card["driver_version"] = dev.get("driver_version")
        card["uid"] = bdf_to_cdi_uid(bdf, dev.get("pci_device_id", ""))
        try:
            detail = json.loads(
                _run_xpu_smi("discovery", "-d", str(dev["device_id"]), "-j"),
            )
            card["driver_version"] = detail.get("driver_version")
            if detail.get("memory_physical_size_byte"):
                card["mem_total"] = float(detail["memory_physical_size_byte"])
        except Exception:
            debug_log_exception(logger, "Failed to query xpu-smi device detail")
    try:
        text = _run_xpu_smi("dump", "-d", "-1", "-m", "0,1,3,18", "-n", "1")
        rows = [r for r in csv.reader(text.splitlines()) if r]
        header = next(
            (i for i, r in enumerate(rows) if r[0].strip().startswith("Timestamp")),
            None,
        )
        if header is not None:
            names = [c.strip() for c in rows[header]]
            for r in rows[header + 1 :]:
                vals = dict(zip(names, (c.strip() for c in r), strict=False))
                bdf = by_id.get(int(vals.get("DeviceId", "-1")))
                if bdf is None:
                    continue
                card = cards[bdf]
                for k, v in vals.items():
                    try:
                        f = float(v)
                    except ValueError:
                        continue
                    if k.startswith("Average % utilization"):
                        card["util"] = f / 100
                    elif k.startswith("GPU Memory Used"):
                        card["mem_used"] = f * 1024 * 1024
                    elif k.startswith("GPU Power"):
                        card["power"] = f
                    elif k.startswith("GPU Core Temperature"):
                        card["temp"] = f
    except Exception:
        debug_log_exception(logger, "Failed to query xpu-smi usage")
    return cards


class IntelDetector(Detector):
    """
    Detect Intel XPUs (e.g. Arc Pro B60) with the `xpu-smi` CLI.
    The device uuid is the Intel CDI device name, so it can be requested
    as `intel.com/gpu=<uuid>` through CDI.
    """

    @staticmethod
    @lru_cache(maxsize=1)
    def is_supported() -> bool:
        """
        Check if the Intel detector is supported, i.e. enabled and `xpu-smi`
        reports at least one GPU.
        """
        if envs.GPUSTACK_RUNTIME_DETECT.lower() not in ("auto", "intel"):
            logger.debug("Intel detection is disabled by environment variable")
            return False
        if not shutil.which("xpu-smi"):
            logger.debug("xpu-smi is not available")
            return False
        try:
            return bool(collect_from_xpu_smi())
        except Exception:
            debug_log_exception(logger, "Failed to query xpu-smi")
            return False

    def __init__(self):
        super().__init__(ManufacturerEnum.INTEL)

    @staticmethod
    def _sorted(cards: dict[str, dict]) -> list[dict]:
        # Stable index: sorted by PCI BDF.
        return [cards[k] for k in sorted(cards)]

    def detect_info(self) -> Devices | None:
        """
        Detect Intel XPU inventory, without usage metrics.
        """
        if not self.is_supported():
            return None

        ret: Devices = []
        try:
            for idx, card in enumerate(self._sorted(collect_from_xpu_smi())):
                bdf = card["bdf"]
                appendix = {"pci_bdf": bdf}
                if card.get("vendor"):
                    appendix["vendor"] = card["vendor"]
                numa = get_numa_node_by_bdf(bdf)
                if numa:
                    appendix["numa"] = numa
                ret.append(
                    Device(
                        manufacturer=self.manufacturer,
                        index=idx,
                        name=card.get("name") or "Intel XPU",
                        uuid=card["uid"],
                        driver_version=card.get("driver_version"),
                        memory=byte_to_mebibyte(int(card.get("mem_total", 0))),
                        memory_status=DeviceMemoryStatusEnum.HEALTHY,
                        appendix=appendix,
                    ),
                )
        except Exception:
            debug_log_exception(logger, "Failed to process Intel devices fetching")
            raise
        return ret

    def detect_usage(self, devices: Devices | None = None) -> Devices | None:
        """
        Fetch the usage of Intel XPUs, merged into the given devices in place.
        """
        if not self.is_supported():
            return None

        if devices is None:
            devices = self.detect_info()
            if devices is None:
                return None

        usages: Devices = []
        try:
            for card in self._sorted(collect_from_xpu_smi()):
                total = byte_to_mebibyte(int(card.get("mem_total", 0)))
                used = byte_to_mebibyte(int(card.get("mem_used", 0)))
                usages.append(
                    Device(
                        uuid=card["uid"],
                        cores_utilization=card.get("util", 0) * 100,
                        memory_used=used,
                        memory_utilization=get_utilization(used, total),
                        memory_status=DeviceMemoryStatusEnum.HEALTHY,
                        temperature=card.get("temp"),
                        power_used=card.get("power"),
                    ),
                )
        except Exception:
            debug_log_exception(logger, "Failed to process Intel devices usage")
            raise
        return merge_devices_usage(devices, usages)

    def get_topology(self, devices: Devices | None = None) -> Topology | None:
        """
        Intel topology: only NUMA/CPU affinities; distances stay unknown.
        """
        if devices is None:
            devices = self.detect_info()
            if devices is None:
                return None

        ret = Topology(
            manufacturer=self.manufacturer,
            devices_count=len(devices),
        )
        for i, dev in enumerate(devices):
            ret.devices_numa_affinities[i] = dev.appendix.get("numa", "")
            ret.devices_cpu_affinities[i] = map_numa_node_to_cpu_affinity(
                ret.devices_numa_affinities[i],
            )
        return ret
